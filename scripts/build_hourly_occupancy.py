"""Build the clean hourly occupied/empty table for one room from the raw export.

Reads the raw occupancy CSV (read-only), keeps one space's events, runs
:func:`smart_infra.occupancy.build_hourly_table`, and writes:

- ``data/processed/<room>_hourly.csv``: the hourly table (untracked, derived
  from the raw data);
- ``reports/<room>_hourly_summary.md``: rows removed and hours flagged per
  cleaning rule, plus coverage figures.

Usage (from the repository root)::

    python scripts/build_hourly_occupancy.py [--room G.20] [--datasets Datasets]
                                             [--threshold 1] [--max-gap 24h]

Requires ``duckdb`` (the raw file is ~1.6 GB, so the space filter is pushed
into DuckDB rather than loading every row into pandas).
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import duckdb
import pandas as pd

from smart_infra.occupancy import SPACE_IDS, build_hourly_table

OCC_CSV = "5occupancySensor_MayToDec2024_9MRows/5occupancySensor_MayToDec2024_9MRows.csv"

RULES = {
    "OCC-RANGE-01": "Headcount missing or negative: row removed",
    "OCC-DUP-01": "Row identical apart from `id`: duplicate removed",
    "OCC-DUP-02": "Same timestamp, different values: latest `id` kept",
    "OCC-GAP-01": "Hour inside a silence > max gap covering weekday working hours: flagged `outage`",
    "OCC-NIGHT-01": "Occupied hour between 01:00 and 05:00: flagged `night_detection`",
}


def load_space_events(csv_path: Path, space_id: str) -> pd.DataFrame:
    """Read one space's events from the raw CSV in the format ``clean_events`` expects."""
    # Timestamps are fetched as epoch milliseconds so no timezone conversion
    # happens inside DuckDB; pandas then attaches UTC explicitly.
    events = duckdb.sql(f"""
        SELECT id, epoch_ms(collecteddate::TIMESTAMPTZ) AS ms,
               occupancystatus AS status, headcount
        FROM read_csv('{csv_path.as_posix()}', header=true, nullstr='NULL',
                      types={{'collecteddate': 'VARCHAR'}})
        WHERE floorspaceid = '{space_id}'""").df()
    events["timestamp"] = pd.to_datetime(events.pop("ms"), unit="ms", utc=True)
    return events


def write_summary(path: Path, room: str, args: argparse.Namespace, n_raw: int,
                  hourly: pd.DataFrame, log: dict[str, int], seconds: float) -> None:
    """Write the per-rule cleaning summary as Markdown."""
    usable = hourly[~hourly["outage"]]
    lines = [
        f"# {room} hourly occupancy table: cleaning summary",
        "",
        f"Generated by `python scripts/build_hourly_occupancy.py --room {room} "
        f"--threshold {args.threshold} --max-gap {args.max_gap}` in {seconds:.0f} s.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Space ID | `{SPACE_IDS[room]}` |",
        f"| Raw events | {n_raw:,} |",
        f"| First hour | {hourly.index[0]:%Y-%m-%d %H:%M %Z} |",
        f"| Last hour | {hourly.index[-1]:%Y-%m-%d %H:%M %Z} |",
        f"| Hours in table | {len(hourly):,} |",
        f"| Hours flagged as outage | {int(hourly['outage'].sum()):,} |",
        f"| Usable hours (not outage) | {len(usable):,} |",
        f"| Occupied share of usable hours | {usable['occupied'].mean():.1%} |",
        "",
        "## Cleaning rules",
        "",
        "| Rule | Action | Count |",
        "|---|---|---|",
        *(f"| `{rule}` | {desc} | {log[rule]:,} |" for rule, desc in RULES.items()),
        "",
        "## Outage periods",
        "",
        "| From | To | Hours |",
        "|---|---|---|",
    ]
    # Group consecutive outage hours into periods.
    out = hourly["outage"]
    period = (out != out.shift()).cumsum()[out]
    for _, hours in out[out].groupby(period):
        lines.append(f"| {hours.index[0]:%Y-%m-%d %H:%M} | "
                     f"{hours.index[-1] + pd.Timedelta('1h'):%Y-%m-%d %H:%M} | {len(hours)} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--room", default="G.20", choices=sorted(SPACE_IDS), help="room to process")
    parser.add_argument("--datasets", type=Path, default=Path("Datasets"), help="folder holding the raw exports")
    parser.add_argument("--threshold", type=int, default=1, help="minimum headcount for an occupied hour")
    parser.add_argument("--max-gap", default="24h", help="shortest silence that can count as an outage")
    args = parser.parse_args()

    started = time.perf_counter()
    events = load_space_events(args.datasets / OCC_CSV, SPACE_IDS[args.room])
    hourly, log = build_hourly_table(events, occupied_threshold=args.threshold, max_gap=args.max_gap)
    seconds = time.perf_counter() - started

    stem = args.room.replace(".", "").lower()
    out_csv = Path("data/processed") / f"{stem}_hourly.csv"
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    hourly.to_csv(out_csv, date_format="%Y-%m-%dT%H:%M%z")
    summary = Path("reports") / f"{stem}_hourly_summary.md"
    write_summary(summary, args.room, args, len(events), hourly, log, seconds)

    print(f"{len(events):,} events -> {len(hourly):,} hours in {seconds:.1f} s")
    print(f"wrote {out_csv} and {summary}")
    for rule, count in log.items():
        print(f"  {rule}: {count:,}")


if __name__ == "__main__":
    main()
