"""Build clean occupied/empty tables for one room from the raw export.

Reads the raw occupancy CSV (read-only), keeps one space's events, runs
:func:`smart_infra.occupancy.build_occupancy_table` at each requested
resolution, and writes:

- ``data/processed/<room>_<resolution>.csv``: one table per resolution
  (untracked, derived from the raw data);
- ``reports/<room>_occupancy_summary.md``: coverage and occupied share at each
  resolution, plus rows removed and intervals flagged per cleaning rule.

Usage (from the repository root)::

    python scripts/build_occupancy_tables.py [--room G.20] [--datasets Datasets]
                                             [--resolution all|10min|30min|1h]
                                             [--threshold 1] [--max-gap 24h]

Requires ``duckdb`` (the raw file is ~1.6 GB, so the space filter is pushed
into DuckDB rather than loading every row into pandas).
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import duckdb
import pandas as pd

from smart_infra.occupancy import RESOLUTIONS, SPACE_IDS, build_occupancy_table

OCC_CSV = "5occupancySensor_MayToDec2024_9MRows/5occupancySensor_MayToDec2024_9MRows.csv"

RULES = {
    "OCC-RANGE-01": "Headcount missing or negative: row removed",
    "OCC-DUP-01": "Row identical apart from `id`: duplicate removed",
    "OCC-DUP-02": "Same timestamp, different values: latest `id` kept",
    "OCC-GAP-01": "Interval inside a silence > max gap covering weekday working hours: flagged `outage`",
    "OCC-NIGHT-01": "Occupied interval between 01:00 and 05:00: flagged `night_detection`",
}
EVENT_RULES = ("OCC-RANGE-01", "OCC-DUP-01", "OCC-DUP-02")


def load_space_events(csv_path: Path, space_id: str) -> pd.DataFrame:
    """Read one space's events from the raw CSV in the format ``clean_events`` expects."""
    # Timestamps are fetched as epoch milliseconds so no timezone conversion
    # happens inside DuckDB; pandas then attaches UTC explicitly.
    events = duckdb.sql(f"""
        SELECT id, epoch_ms(collecteddate::TIMESTAMPTZ) AS ms,
               occupancystatus AS status, headcount
        FROM read_csv('{csv_path.as_posix()}', header=true, nullstr='NULL',
                      types={{'collecteddate': 'VARCHAR'}})
        WHERE floorspaceid = '{space_id}'""").df()
    events["timestamp"] = pd.to_datetime(events.pop("ms"), unit="ms", utc=True)
    return events


def write_summary(path: Path, room: str, args: argparse.Namespace, n_raw: int,
                  results: dict[str, tuple[pd.DataFrame, dict[str, int], float]]) -> None:
    """Write the per-resolution and per-rule cleaning summary as Markdown."""
    any_table = next(iter(results.values()))[0]
    any_log = next(iter(results.values()))[1]
    lines = [
        f"# {room} occupancy tables: cleaning summary",
        "",
        f"Generated by `python scripts/build_occupancy_tables.py --room {room} --resolution {args.resolution} "
        f"--threshold {args.threshold} --max-gap {args.max_gap}`.",
        "",
        f"- Space ID: `{SPACE_IDS[room]}`",
        f"- Raw events: {n_raw:,}",
        f"- Period: {any_table.index[0]:%Y-%m-%d %H:%M %Z} to {any_table.index[-1]:%Y-%m-%d %H:%M %Z}",
        "",
        "## By resolution",
        "",
        "The same events give a lower occupied share at finer resolution, because a short visit marks a "
        "whole interval as occupied.",
        "",
        "| Resolution | Intervals | Flagged outage | Usable | Occupied share of usable | Build time (s) |",
        "|---|---|---|---|---|---|",
    ]
    for res, (table, _, seconds) in results.items():
        usable = table[~table["outage"]]
        lines.append(f"| {res} | {len(table):,} | {int(table['outage'].sum()):,} | {len(usable):,} | "
                     f"{usable['occupied'].mean():.1%} | {seconds:.1f} |")

    lines += ["", "## Cleaning rules", "", "Event rules are applied before aggregation, so their counts are the "
              "same at every resolution.", "", "| Rule | Action | " + " | ".join(results) + " |",
              "|---|---|" + "---|" * len(results)]
    for rule, desc in RULES.items():
        lines.append(f"| `{rule}` | {desc} | " + " | ".join(f"{log[rule]:,}" for _, log, _ in results.values()) + " |")

    # Outage periods are the same at every resolution up to interval rounding;
    # list them from the finest table built.
    finest = results[min(results, key=pd.Timedelta)][0]
    out = finest["outage"]
    period = (out != out.shift()).cumsum()[out]
    lines += ["", "## Outage periods", "", "| From | To | Hours |", "|---|---|---|"]
    step = finest.index[1] - finest.index[0]
    for _, block in out[out].groupby(period):
        lines.append(f"| {block.index[0]:%Y-%m-%d %H:%M} | {block.index[-1] + step:%Y-%m-%d %H:%M} | "
                     f"{len(block) * step / pd.Timedelta('1h'):.1f} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--room", default="G.20", choices=sorted(SPACE_IDS), help="room to process")
    parser.add_argument("--datasets", type=Path, default=Path("Datasets"), help="folder holding the raw exports")
    parser.add_argument("--resolution", default="all", choices=["all", *RESOLUTIONS], help="interval length")
    parser.add_argument("--threshold", type=int, default=1, help="minimum headcount for an occupied interval")
    parser.add_argument("--max-gap", default="24h", help="shortest silence that can count as an outage")
    args = parser.parse_args()

    started = time.perf_counter()
    events = load_space_events(args.datasets / OCC_CSV, SPACE_IDS[args.room])
    print(f"loaded {len(events):,} events in {time.perf_counter() - started:.1f} s")

    stem = args.room.replace(".", "").lower()
    out_dir = Path("data/processed")
    out_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    for res in RESOLUTIONS if args.resolution == "all" else [args.resolution]:
        started = time.perf_counter()
        table, log = build_occupancy_table(events, resolution=res, occupied_threshold=args.threshold,
                                           max_gap=args.max_gap)
        seconds = time.perf_counter() - started
        results[res] = (table, log, seconds)
        out_csv = out_dir / f"{stem}_{res}.csv"
        table.to_csv(out_csv, date_format="%Y-%m-%dT%H:%M%z")
        usable = table[~table["outage"]]
        print(f"{res:>5}: {len(table):,} intervals, {usable['occupied'].mean():.1%} occupied, "
              f"{seconds:.1f} s -> {out_csv}")

    summary = Path("reports") / f"{stem}_occupancy_summary.md"
    write_summary(summary, args.room, args, len(events), results)
    print(f"wrote {summary}")


if __name__ == "__main__":
    main()
