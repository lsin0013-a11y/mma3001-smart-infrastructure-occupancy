"""Compare forecast horizons for the hybrid ventilation strategy.

A longer horizon gives the controller more warning of arrivals but a less
accurate forecast. For each horizon this trains the gradient-boosting
forecast (tuned settings from ``run_forecast.py``) at 5-min resolution, then
simulates the hybrid strategy (larger of the live sensor and the forecast)
over the 2026 test period, as in ``ventilation_study.py``.

Writes ``reports/horizon_comparison.csv`` and ``reports/horizon_comparison.md``.

Usage (from the repository root, after ``build_occupancy_tables.py``)::

    python scripts/horizon_comparison.py [--room G.20] [--datasets Datasets]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from build_occupancy_tables import OCC_CSV, load_space_events
from smart_infra.forecasting import TARGET, evaluate, make_dataset, make_models, split_by_date
from smart_infra.occupancy import SPACE_IDS, build_occupancy_table, read_table
from smart_infra.ventilation import RATE_PER_PERSON, assess, infiltration_airflow, simulate_co2
from ventilation_study import DT, TEST_START, fixed_schedule

HORIZONS = ["10min", "20min", "30min", "1h"]
BOOSTING = {"learning_rate": 0.05, "max_leaf_nodes": 15, "max_iter": 300}  # from run_forecast.py tuning
RES = "5min"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--room", default="G.20", choices=sorted(SPACE_IDS))
    parser.add_argument("--datasets", type=Path, default=Path("Datasets"))
    args = parser.parse_args()
    stem = args.room.replace(".", "").lower()

    events = load_space_events(args.datasets / OCC_CSV, SPACE_IDS[args.room])
    minute, _ = build_occupancy_table(events, resolution="1min")
    minute = minute[minute.index >= pd.Timestamp(TEST_START, tz=minute.index.tz)]
    people = minute["mean_headcount"].where(~minute["outage"], 0.0).to_numpy()
    fixed = fixed_schedule(minute.index)
    fixed_co2 = simulate_co2(people, fixed + infiltration_airflow(), DT)

    table = read_table(Path("data/processed") / f"{stem}_{RES}.csv")
    live = table["mean_headcount"].where(~table["outage"]).shift(1)
    # Floor in UTC: the local clock repeats an hour when daylight saving ends.
    slot = minute.index.tz_convert("UTC").floor(RES).tz_convert(minute.index.tz)

    rows = []
    for horizon in HORIZONS:
        train, test = split_by_date(make_dataset(table, horizon=horizon))
        model = make_models(BOOSTING)["boosting"].fit(train.drop(columns=TARGET), train[TARGET])
        forecast = pd.Series(model.predict(test.drop(columns=TARGET)), index=test.index)
        hybrid = np.maximum(live.reindex(test.index), forecast)
        airflow = (RATE_PER_PERSON * hybrid).reindex(slot).fillna(0.0).to_numpy()
        valid = slot.isin(test.index) & ~minute["outage"].to_numpy()
        co2 = simulate_co2(people, airflow + infiltration_airflow(), DT)
        result = assess(people, airflow, co2, DT, mask=valid)
        # Scored over the same minutes as ventilation_study.py.
        fixed_air = assess(people, fixed, fixed_co2, DT, mask=valid)["air_m3"]
        rows.append({"horizon": horizon, "forecast_mae": evaluate(test[TARGET], forecast.to_numpy())["mae"],
                     "air_vs_fixed": result["air_m3"] / fixed_air, **result})
        print(f"{horizon:>6}: MAE {rows[-1]['forecast_mae']:.3f}  air {rows[-1]['air_vs_fixed']:.1%}  "
              f"person-h over {result['person_hours_over_limit']:.1f}", flush=True)

    results = pd.DataFrame(rows)
    results.to_csv("reports/horizon_comparison.csv", index=False, float_format="%.4f")
    lines = [
        f"# {args.room} forecast horizon comparison: hybrid strategy, 5-min control",
        "",
        "Gradient-boosting forecast issued each horizon ahead; the hybrid supplies air for the larger of the "
        "live sensor (previous interval) and the forecast. 2026 test period, sensor outages excluded. *Air vs "
        "fixed* is outdoor air supplied relative to the fixed schedule.",
        "",
        f"Generated by `python scripts/horizon_comparison.py --room {args.room}`.",
        "",
        "| Horizon | Forecast MAE (people) | Air vs fixed | Person-hours > limit | Peak (ppm) |",
        "|---|---|---|---|---|",
    ]
    for r in results.itertuples():
        lines.append(f"| {r.horizon} | {r.forecast_mae:.3f} | {r.air_vs_fixed:.1%} | "
                     f"{r.person_hours_over_limit:.1f} | {r.peak_ppm:.0f} |")
    Path("reports/horizon_comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
