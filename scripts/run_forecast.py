"""Train and test the headcount forecasts for one room.

For each resolution (5 min is the main one; 10 min, 30 min and 1 h are for
comparison) this builds the forecasting dataset, tunes the gradient-boosting
settings by time-series cross-validation on the training period only, fits
every model in :func:`smart_infra.forecasting.make_models` on 2024-2025 and
tests it on 2026.

Writes:

- ``reports/forecast_results.csv`` and ``reports/forecast_results.md``:
  accuracy, bias and run time per model and resolution;
- ``data/processed/<room>_forecast_<resolution>.csv``: test-period
  forecasts from every model (untracked; used by the ventilation study).

Usage (from the repository root, after ``build_occupancy_tables.py``)::

    python scripts/run_forecast.py [--room G.20] [--horizon 10min]
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import pandas as pd

from smart_infra.forecasting import TARGET, evaluate, make_dataset, make_models, split_by_date, tune_boosting
from smart_infra.occupancy import read_table

RESOLUTIONS = ["5min", "10min", "30min", "1h"]
GRID = [
    {"learning_rate": lr, "max_leaf_nodes": leaves, "max_iter": 300}
    for lr in (0.05, 0.1) for leaves in (15, 31)
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--room", default="G.20")
    parser.add_argument("--horizon", default="10min", help="how far ahead the forecast is issued")
    args = parser.parse_args()
    stem = args.room.replace(".", "").lower()

    rows, tuning_notes = [], []
    for res in RESOLUTIONS:
        table = read_table(Path("data/processed") / f"{stem}_{res}.csv")
        data = make_dataset(table, horizon=args.horizon)
        train, test = split_by_date(data)
        X_train, y_train = train.drop(columns=TARGET), train[TARGET]
        X_test, y_test = test.drop(columns=TARGET), test[TARGET]

        started = time.perf_counter()
        best, scores = tune_boosting(train, GRID)
        tuning_notes.append((res, best, scores, time.perf_counter() - started))
        print(f"{res}: tuned {best} ({len(train):,} train / {len(test):,} test rows)", flush=True)

        forecasts = pd.DataFrame({"observed": y_test})
        for name, model in make_models(best).items():
            started = time.perf_counter()
            model.fit(X_train, y_train)
            fit_s = time.perf_counter() - started
            started = time.perf_counter()
            pred = model.predict(X_test)
            predict_s = time.perf_counter() - started
            forecasts[name] = pred

            quantile = 0.9 if name.endswith("q90") else None
            # Daytime on weekdays is when ventilation matters most.
            day = ((X_test["day_of_week"] < 5) & (X_test["minute_of_day"] >= 8 * 60)
                   & (X_test["minute_of_day"] < 20 * 60)).to_numpy()
            overall = evaluate(y_test, pred, quantile)
            daytime = evaluate(y_test[day], pred[day])
            rows.append({"resolution": res, "model": name, **overall,
                         "daytime_mae": daytime["mae"], "fit_s": fit_s, "predict_s": predict_s})
            print(f"  {name:<24} MAE {overall['mae']:.3f}  daytime MAE {daytime['mae']:.3f}  "
                  f"bias {overall['bias']:+.3f}  under {overall['under_share']:.0%}  fit {fit_s:.1f}s", flush=True)
        forecasts.to_csv(Path("data/processed") / f"{stem}_forecast_{res}.csv",
                         date_format="%Y-%m-%dT%H:%M%z", float_format="%.4f")

    results = pd.DataFrame(rows)
    results.to_csv("reports/forecast_results.csv", index=False, float_format="%.4f")
    write_markdown(results, tuning_notes, args)
    print("wrote reports/forecast_results.csv and reports/forecast_results.md")


def write_markdown(results: pd.DataFrame, tuning_notes: list, args: argparse.Namespace) -> None:
    """Summarise accuracy and tuning as Markdown."""
    lines = [
        f"# {args.room} headcount forecast: test results",
        "",
        f"Forecast issued {args.horizon} ahead (one interval ahead at 30 min and 1 h). Trained on 2024-03 to 2025-12, "
        "tested on 2026-01-01 to 2026-04-22; outage intervals excluded. Errors are in people (mean headcount "
        "per interval). *Daytime* = weekdays 08:00-20:00. *Under* = share of intervals forecast below the "
        "observed headcount (the room would be under-ventilated).",
        "",
        f"Generated by `python scripts/run_forecast.py --room {args.room} --horizon {args.horizon}`.",
        "",
    ]
    for res, group in results.groupby("resolution", sort=False):
        lines += [f"## {res}", "", "| Model | MAE | Daytime MAE | RMSE | Bias | Under | Fit (s) | Predict (s) |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in group.itertuples():
            lines.append(f"| {r.model} | {r.mae:.3f} | {r.daytime_mae:.3f} | {r.rmse:.3f} | {r.bias:+.3f} | "
                         f"{r.under_share:.0%} | {r.fit_s:.2f} | {r.predict_s:.3f} |")
        lines.append("")
    lines += ["## Gradient-boosting tuning (time-series CV on the training period only)", "",
              "| Resolution | Chosen settings | Candidates: mean validation MAE | Tuning time (s) |", "|---|---|---|---|"]
    for res, best, scores, seconds in tuning_notes:
        cands = "; ".join(f"lr {r.learning_rate}, leaves {r.max_leaf_nodes}: {r.mean_mae:.4f}"
                          for r in scores.itertuples())
        lines.append(f"| {res} | {best} | {cands} | {seconds:.0f} |")
    Path("reports/forecast_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
